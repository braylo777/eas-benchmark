"""Write results/V02_RESULTS.md from the v0.2 JSON files. Standard library only."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"


def pct(c):
    return f"{100*c['est']:.1f}% [{100*c['lo']:.1f}, {100*c['hi']:.1f}]"


def main():
    mc = json.loads((R / "rust_montecarlo.json").read_text())
    bh = json.loads((R / "behaviour_summary.json").read_text())
    pb = json.loads((R / "probe_bootstrap.json").read_text())
    m = mc["main"]
    sv = mc["seed_variance"]
    L = ["# v0.2 results (auto-generated by scripts/v02_report.py)", ""]
    L += [
        "## Study S — SIMULATION (Rust re-run of the scoring engine; assumed generators)",
        "",
    ]
    L += [
        f"{mc['trials_total']:,} simulated trials: main + 25%-covert runs at {mc['n_per_class']:,}/class, "
        f"plus {sv['seeds']} extra seeds of each. 95% percentile bootstrap ({m['false_pass_at_0.65']['n_boot']} resamples).",
        "",
    ]
    L += [
        "| metric | Rust v0.2 (bootstrap 95% CI) | seed mean ± SD (min–max) | Python v0.1 |",
        "|---|---|---|---|",
    ]
    ref = mc["python_reference_v01"]
    rows = [
        (
            "false-pass at V ≥ 0.65",
            m["false_pass_at_0.65"]["bootstrap"],
            sv["false_pass"],
            ref["false_pass"],
        ),
        (
            "false-veto at V ≥ 0.65",
            m["false_veto_at_0.65"]["bootstrap"],
            sv["false_veto"],
            ref["false_veto"],
        ),
        (
            "prime-gate veto rate",
            m["gate_veto_rate"]["wilson"],
            sv["gate_veto"],
            ref["gate_veto"],
        ),
        (
            "covert unsafe pass (25% covert)",
            mc["covert25"]["covert_unsafe_false_pass"]["bootstrap"],
            sv["covert_unsafe_false_pass"],
            ref["covert_pass"],
        ),
    ]
    for name, ci, s, py in rows:
        L.append(
            f"| {name} | {pct(ci)} | {100*s['mean']:.2f}% ± {100*s['sd']:.2f} ({100*s['min']:.2f}–{100*s['max']:.2f}) | {100*py:.1f}% |"
        )
    a = m["auc_V_benign_vs_unsafe"]["bootstrap"]
    L.append(
        f"| AUC of V | {a['est']:.3f} [{a['lo']:.3f}, {a['hi']:.3f}] ({m['auc_V_benign_vs_unsafe']['n_boot']} resamples) | — | {ref['auc_V']:.3f} |"
    )
    e = m["equal_error"]
    L += [
        "",
        f"Equal-error threshold: {e['threshold']:.2f} (false-pass {100*e['false_pass']:.1f}%, false-veto {100*e['false_veto']:.1f}%).",
        "",
    ]

    L += ["## Study B — MEASURED (local Ollama models, surface answers only)", ""]
    L += [
        f"{bh['trials_total']:,} model trials. Method: {bh['method']}. CIs: bootstrap over the 680 statements, "
        f"{bh['n_boot']} resamples. p-values: exact McNemar, Holm-corrected across models.",
        "",
    ]
    L += [
        "| model (Ollama tag) | params / quant | neutral | mislead | flatter | agree | flip (mislead) | flip (flatter) | H2 p_holm | H3 p_holm |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for name, x in sorted(bh["models"].items(), key=lambda kv: kv[0]):
        meta = x.get("meta") or {}
        ac, fl, t = x["accuracy"], x["flip_rate"], x["tests"]
        L.append(
            f"| `{name}` | {meta.get('parameter_size','?')} / {meta.get('quantization','?')} | {pct(ac['neutral'])} | {pct(ac['mislead'])} | "
            f"{pct(ac['flatter'])} | {pct(ac['agree'])} | {pct(fl['mislead'])} | {pct(fl['flatter'])} | "
            f"{t['H2_neutral_vs_flatter']['p_holm']:.2g} | {t['H3_flatter_vs_mislead_flips']['p_holm']:.2g} |"
        )
    h = bh["hypotheses"]
    n = h["models"]
    verdict = lambda k: "SUPPORTED" if h[k] > n / 2 else "NOT SUPPORTED"  # noqa: E731
    L += [
        "",
        "### Preregistered hypotheses (docs/PREREGISTRATION.md)",
        "",
        f"- H2 (flatter < neutral accuracy): {h['H2_supported_significant']}/{n} models significant → **{verdict('H2_supported_significant')}**",
        f"- H3 (flatter flips > mislead flips): {h['H3_supported_significant']}/{n} models significant → **{verdict('H3_supported_significant')}**",
        f"- H4 (agree not below neutral): {h['H4_direction_holds']}/{n} models → **{verdict('H4_direction_holds')}**",
        "",
    ]
    L += ["Model digests:", ""]
    for name, x in sorted(bh["models"].items()):
        L.append(f"- `{name}`: `{(x.get('meta') or {}).get('digest','?')}`")

    L += [
        "",
        "## v0.1 probe data — bootstrap re-analysis (no new runs)",
        "",
        f"Source: {pb['source']}. {pb['n_boot']} resamples over held-out statements.",
        "",
        "| model | framing | n | surface acc | probe acc | mismatch | probe − surface |",
        "|---|---|---|---|---|---|---|",
    ]
    for mod, per in pb["models"].items():
        for fr, x in per.items():
            d = x["probe_minus_surface"]
            L.append(
                f"| {mod} | {fr} | {x['n']} | {pct(x['surface_accuracy'])} | {pct(x['probe_accuracy'])} | "
                f"{pct(x['mismatch_rate'])} | {100*d['est']:+.1f} pp [{100*d['lo']:+.1f}, {100*d['hi']:+.1f}] |"
            )
    (R / "V02_RESULTS.md").write_text("\n".join(L) + "\n")
    print("wrote results/V02_RESULTS.md")


if __name__ == "__main__":
    main()
